''' Challenge: DRY (Don't Repeat Yourself)

Objective: Identify redundant code in a script and refactor it into a reusable function. '''
# print() function: It is used to get output.
print('Hello World')
# input() function: It is used to get input from user.
a = int(input("Enter value of a: "))
print(a)
# len() function :  Used to find length of string or list.
b = [ 1,2,3,4]
print(len(b))
# max() function :  Used to find maximum value in the list.
print(max(b))
# bin()
print(bin(3))